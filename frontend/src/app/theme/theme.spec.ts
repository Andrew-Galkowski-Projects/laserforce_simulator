// The app theme (ANG-04b, ADR-0043): the `--lf-*` contract and the Material system roles resolve
// on the document root in light AND dark, and no Side colour is hard-coded outside the token block.
//
// How light/dark is exercised: the test compiles the real global stylesheet (`src/styles.scss`)
// with Sass and injects it into jsdom. jsdom matches no media *feature*, so
// `@media (prefers-color-scheme: dark)` never applies on its own. `emulate()` stands in for the
// OS setting: it rewrites the chosen scheme's media condition to `screen` (which jsdom matches)
// and the other scheme's to `not all`, the same thing a browser does when it evaluates the query.
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { TestBed } from '@angular/core/testing';
import { provideRouter } from '@angular/router';
import { compile } from 'sass';
import { App } from '../app';
import { routes } from '../app.routes';
import { LF_COLOUR_TOKENS, LF_TOKENS, SIDE_ALIASES } from './theme-tokens';

const SRC = join(process.cwd(), 'src');
const STYLES_DIR = join(SRC, 'styles');
const TOKEN_BLOCK = join(STYLES_DIR, '_tokens.scss');
// Generated by `ng generate @angular/material:theme-color`: Material's tonal palettes, not Sides.
const MATERIAL_PALETTES = join(STYLES_DIR, '_theme-colors.scss');

/** Material roles that must resolve in both modes, so Material components follow the theme. */
const MAT_SYS_ROLES = [
  '--mat-sys-primary',
  '--mat-sys-on-primary',
  '--mat-sys-primary-container',
  '--mat-sys-on-primary-container',
  '--mat-sys-secondary',
  '--mat-sys-secondary-container',
  '--mat-sys-tertiary',
  '--mat-sys-error',
  '--mat-sys-on-error',
  '--mat-sys-background',
  '--mat-sys-on-background',
  '--mat-sys-surface',
  '--mat-sys-on-surface',
  '--mat-sys-surface-variant',
  '--mat-sys-on-surface-variant',
  '--mat-sys-surface-dim',
  '--mat-sys-surface-bright',
  '--mat-sys-surface-container-lowest',
  '--mat-sys-surface-container-low',
  '--mat-sys-surface-container',
  '--mat-sys-surface-container-high',
  '--mat-sys-surface-container-highest',
  '--mat-sys-outline',
  '--mat-sys-outline-variant',
  '--mat-sys-inverse-surface',
  '--mat-sys-inverse-on-surface',
  '--mat-sys-inverse-primary',
  '--mat-sys-body-medium',
  '--mat-sys-title-large',
  '--mat-sys-corner-medium',
];

/** The Material roles the theme points at the `--lf-*` contract (the rest come from the palettes). */
const MAT_SYS_FROM_CONTRACT: Record<string, string> = {
  '--mat-sys-primary': '--lf-accent',
  '--mat-sys-background': '--lf-bg',
  '--mat-sys-surface': '--lf-bg',
  '--mat-sys-on-surface': '--lf-text',
  '--mat-sys-on-surface-variant': '--lf-text-muted',
  '--mat-sys-surface-container': '--lf-surface',
  '--mat-sys-outline-variant': '--lf-border',
};

const compiledCss = compile(join(SRC, 'styles.scss'), {
  loadPaths: [join(process.cwd(), 'node_modules')],
  silenceDeprecations: ['import'],
}).css;

type Scheme = 'light' | 'dark';

function emulate(scheme: Scheme): string {
  return compiledCss.replace(
    /\(\s*prefers-color-scheme:\s*(light|dark)\s*\)/g,
    (_match, query: string) => (query === scheme ? 'screen' : 'not all'),
  );
}

function scssFilesUnder(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return scssFilesUnder(path);
    return path.endsWith('.scss') ? [path] : [];
  });
}

function stripComments(scss: string): string {
  return scss.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
}

const COLOUR_LITERAL = /#[0-9a-f]{3,8}\b|\b(?:rgba?|hsla?|oklch|oklab|lab|lch|hwb|color)\(/gi;

/** Every value the token block gives a Side token, in either mode. */
function sideValues(): string[] {
  const block = stripComments(readFileSync(TOKEN_BLOCK, 'utf-8'));
  return [...block.matchAll(/--lf-side-(?:red|blue)[a-z-]*:\s*([^;]+);/g)].map((m) =>
    m[1].trim().toLowerCase(),
  );
}

let styleElement: HTMLStyleElement | undefined;

async function renderApp(scheme: Scheme): Promise<CSSStyleDeclaration> {
  styleElement = document.createElement('style');
  styleElement.textContent = emulate(scheme);
  document.head.appendChild(styleElement);
  TestBed.configureTestingModule({ imports: [App], providers: [provideRouter(routes)] });
  const fixture = TestBed.createComponent(App);
  await fixture.whenStable();
  return getComputedStyle(document.documentElement);
}

function emptyTokens(style: CSSStyleDeclaration, names: readonly string[]): string[] {
  return names.filter((name) => style.getPropertyValue(name).trim() === '');
}

describe('app theme', () => {
  afterEach(() => {
    styleElement?.remove();
    styleElement = undefined;
  });

  for (const scheme of ['light', 'dark'] as const) {
    it(`defines every --lf-* contract token on the root in ${scheme} mode`, async () => {
      const root = await renderApp(scheme);
      expect(emptyTokens(root, LF_TOKENS)).toEqual([]);
    });

    it(`resolves the Material system roles on the root in ${scheme} mode`, async () => {
      const root = await renderApp(scheme);
      expect(emptyTokens(root, MAT_SYS_ROLES)).toEqual([]);
    });

    it(`points the key Material roles at the --lf-* contract in ${scheme} mode`, async () => {
      const root = await renderApp(scheme);
      for (const [role, token] of Object.entries(MAT_SYS_FROM_CONTRACT)) {
        expect(root.getPropertyValue(role), role).toContain(token);
      }
    });

    it(`gives each [data-lf-side] container its own --side* aliases in ${scheme} mode`, async () => {
      await renderApp(scheme);
      const red = document.createElement('div');
      red.dataset['lfSide'] = 'red';
      const blue = document.createElement('div');
      blue.dataset['lfSide'] = 'blue';
      document.body.append(red, blue);
      try {
        for (const alias of SIDE_ALIASES) {
          const suffix = alias.slice('--side'.length);
          expect(getComputedStyle(red).getPropertyValue(alias)).toContain(`--lf-side-red${suffix}`);
          expect(getComputedStyle(blue).getPropertyValue(alias)).toContain(
            `--lf-side-blue${suffix}`,
          );
        }
      } finally {
        red.remove();
        blue.remove();
      }
    });
  }

  it('gives the dark scheme its own value for every colour token', async () => {
    const light = await renderApp('light');
    const lightValues = LF_COLOUR_TOKENS.map((name) => light.getPropertyValue(name).trim());
    styleElement?.remove();
    TestBed.resetTestingModule();
    const dark = await renderApp('dark');
    const unchanged = LF_COLOUR_TOKENS.filter(
      (name, i) => dark.getPropertyValue(name).trim() === lightValues[i],
    );
    expect(unchanged).toEqual([]);
  });

  it('finds the Side values in the token block', () => {
    // 8 Side tokens, light and dark.
    expect(sideValues().length).toBe(16);
  });

  it('keeps colour literals out of every global stylesheet but the token block', () => {
    const globals = [join(SRC, 'styles.scss'), ...scssFilesUnder(STYLES_DIR)].filter(
      (file) => file !== TOKEN_BLOCK && file !== MATERIAL_PALETTES,
    );
    const offenders = globals.flatMap((file) => {
      const hits = stripComments(readFileSync(file, 'utf-8')).match(COLOUR_LITERAL) ?? [];
      return hits.map((hit) => `${relative(SRC, file)}: ${hit}`);
    });
    expect(offenders).toEqual([]);
  });

  it('hard-codes no Side colour in any stylesheet outside the token block', () => {
    const sides = sideValues();
    const offenders = scssFilesUnder(SRC)
      .filter((file) => file !== TOKEN_BLOCK)
      .flatMap((file) => {
        const text = stripComments(readFileSync(file, 'utf-8')).toLowerCase();
        return sides
          .filter((value) => text.includes(value))
          .map((v) => `${relative(SRC, file)}: ${v}`);
      });
    expect(offenders).toEqual([]);
  });
});
